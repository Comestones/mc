import assert from 'node:assert/strict';
import { createDatabase, addProperty, addRow, deleteProperty, changePropertyType, validateDatabaseSchema, normalizeDatabaseSchema } from '../src/utils/databaseUtils.ts';
import { normalizeViewConfig, updateViewConfig, safeCoverUrl } from '../src/utils/databaseViewUtils.ts';

let database = createDatabase('Day 13');
database = addProperty(database, { id: 'image', name: '封面', type: 'url' });
database = addProperty(database, { id: 'status', name: '状态', type: 'select', options: [{ id: 'todo', name: '待办' }] });
assert.equal(normalizeViewConfig(database, undefined).activeView, 'table');
assert.equal(validateDatabaseSchema(database), true);
for (let index = 0; index < 200; index++) database = addRow(database, { 'prop-title': `卡片 ${index}`, status: 'todo' });
const original = database;
database = updateViewConfig(database, { activeView: 'gallery', gallery: { coverPropertyId: 'image', visiblePropertyIds: ['status', 'status', 'missing'] } });
assert.equal(database.rows, original.rows);
assert.equal(database.rowOrder, original.rowOrder);
assert.deepEqual(database.viewConfig.gallery.visiblePropertyIds, ['status']);
assert.equal(validateDatabaseSchema(database), true);
assert.equal(updateViewConfig(database, { activeView: 'gallery' }), database);
const damaged = { ...database, viewConfig: { ...database.viewConfig, gallery: { coverPropertyId: 'status', visiblePropertyIds: ['missing'] } } };
assert.equal(validateDatabaseSchema(damaged), false);
assert.equal(validateDatabaseSchema(normalizeDatabaseSchema(damaged)), true);
assert.equal(safeCoverUrl('https://example.com/image.png'), 'https://example.com/image.png');
for (const url of ['javascript:alert(1)', 'data:image/png;base64,AAAA', 'mailto:test@example.com', '//example.com/image', 'https://user:pass@example.com/image', 'https://example.com/\nimage']) assert.equal(safeCoverUrl(url), null);
const withoutCover = deleteProperty(database, 'image');
assert.equal(withoutCover.viewConfig.gallery.coverPropertyId, null);
assert.equal(validateDatabaseSchema(withoutCover), true);
const withoutGroup = changePropertyType(database, 'status', 'text');
assert.equal(withoutGroup.viewConfig.boardGroupPropertyId, null);
assert.equal(validateDatabaseSchema(withoutGroup), true);
const roundtrip = JSON.parse(JSON.stringify(database));
assert.equal(validateDatabaseSchema(roundtrip), true);
assert.deepEqual(roundtrip.viewConfig, database.viewConfig);
console.log('Day 13 配置契约、旧库兼容、200 行无损视图更新、安全封面和 JSON 持久化验收通过');
